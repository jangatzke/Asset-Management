/**
 * Form primitives (Stage 8 / MT-5) — `Field`, `FormRow`, `FormSection`.
 *
 * Tailwind-only, semantic design tokens (no MUI). Labels/hints/errors stay in
 * the consuming pages (i18n); this module only provides the consistent markup,
 * ID wiring and visual treatment.
 *
 * ## ID / aria-describedby pattern (the ONE supported variant)
 * `Field` owns all ID logic via React context:
 *   - It derives a stable base id from `htmlFor` if given, otherwise from
 *     `useId()`. The label gets `id={base}-label` and `htmlFor={base}`.
 *   - Hint/error nodes get deterministic ids `${base}-hint` / `${base}-error`
 *     and are joined into a single `describedBy` string.
 *   - Consumers read the wiring with the `useFieldProps()` hook INSIDE a child
 *     component of `Field` and spread it onto their control:
 *
 *       const { id, describedBy, invalid } = useFieldProps();
 *       <input id={id} aria-describedby={describedBy} aria-invalid={invalid || undefined}
 *              className={fieldControlClass(invalid)} />
 *
 *   This keeps pages free of manual ID bookkeeping while the actual `<input>`
 *   markup (name, value, onChange, type) remains fully in page control.
 *
 * `fieldControlClass(invalid)` is exported so consumers get a consistent input
 * look (height from Stage 4 control tokens, focus ring, disabled surface).
 */

import React, { createContext, useContext, useId } from 'react';

/* -------------------------------------------------------------------------- */
/* Shared control styling                                                      */
/* -------------------------------------------------------------------------- */

/**
 * Consistent visual treatment for form controls used inside `Field`.
 * Control height follows the Stage 4 standard (`min-h-[2.25rem]`). The invalid
 * state swaps the border to the critical foreground token — pair it with
 * `aria-invalid` from `useFieldProps()` for screen readers.
 */
// eslint-disable-next-line react-refresh/only-export-components -- Shared class helper must stay colocated with the Field primitives it styles.
export const fieldControlClass = (invalid?: boolean): string =>
  [
    'w-full min-h-[2.25rem] rounded-md border bg-surface-default px-3 text-body1 text-text-primary',
    invalid ? 'border-status-critical-fg' : 'border-border-strong',
    'focus-visible:outline-focus-ring focus-visible:ring-focus-ring-offset',
    'disabled:bg-surface-sunken disabled:text-text-muted',
  ].join(' ');

/* -------------------------------------------------------------------------- */
/* FieldContext + useFieldProps                                                */
/* -------------------------------------------------------------------------- */

interface FieldContextValue {
  /** Control id that the label points at (`htmlFor`). */
  id: string;
  /** Joined ids of hint/error nodes for `aria-describedby`, or undefined. */
  describedBy?: string;
  /** True when the field currently shows an error. */
  invalid: boolean;
}

const FieldContext = createContext<FieldContextValue | null>(null);

/**
 * Access the ID wiring generated by the surrounding `Field`. Must be called in
 * a component rendered as a descendant of `Field`; returns null otherwise so it
 * is safe to use in shared controls that may live outside a field.
 */
// eslint-disable-next-line react-refresh/only-export-components -- Context hook must remain exported with its provider for stable imports.
export const useFieldProps = (): FieldContextValue | null => useContext(FieldContext);

/* -------------------------------------------------------------------------- */
/* Field                                                                       */
/* -------------------------------------------------------------------------- */

type FieldProps = {
  label?: React.ReactNode;
  htmlFor?: string;
  /** Renders the required asterisk in `text-status-critical-fg`. */
  required?: boolean;
  /** Helper text below the control (`text-body2 text-text-muted`). */
  hint?: React.ReactNode;
  /** Error message announced via `role="alert"`; marks the field invalid. */
  error?: React.ReactNode;
  children: React.ReactNode; // Input/Select/Textarea provided by the page
  className?: string;
};

/**
 * Label + hint/error wrapper for a single form control. See module docs for the
 * `useFieldProps()` wiring pattern. If no child consumes the context, pass an
 * explicit `htmlFor` and set `id`/`aria-describedby` on your input yourself —
 * the label/hint/error markup below still works standalone.
 */
export const Field: React.FC<FieldProps> = ({
  label,
  htmlFor,
  required,
  hint,
  error,
  children,
  className,
}) => {
  const reactId = useId();
  const base = htmlFor || `field${reactId.replace(/:/g, '')}`;
  // Only reference ids that actually render: the hint paragraph is hidden while
  // an error is shown, so its id must not appear in aria-describedby.
  const hintId = hint && !error ? `${base}-hint` : undefined;
  const errorId = error ? `${base}-error` : undefined;
  const describedBy = [hintId, errorId].filter(Boolean).join(' ') || undefined;
  const invalid = Boolean(error);

  const ctx: FieldContextValue = { id: base, describedBy, invalid };

  return (
    <FieldContext.Provider value={ctx}>
      <div className={`flex flex-col gap-1 ${className ?? ''}`.trim()}>
        {label ? (
          <label htmlFor={base} className="text-body2 font-medium text-text-secondary">
            {label}
            {required ? (
              <span aria-hidden="true" className="ml-0.5 text-status-critical-fg">*</span>
            ) : null}
          </label>
        ) : null}
        {children}
        {hint && !error ? (
          <p id={hintId} className="text-body2 text-text-muted">
            {hint}
          </p>
        ) : null}
        {error ? (
          <p id={errorId} role="alert" aria-live="polite" className="text-body2 text-status-critical-fg">
            {error}
          </p>
        ) : null}
      </div>
    </FieldContext.Provider>
  );
};

/* -------------------------------------------------------------------------- */
/* FormRow                                                                     */
/* -------------------------------------------------------------------------- */

type FormRowProps = {
  /** Column count at `lg` and above; always single-column below. */
  columns?: 1 | 2 | 3;
  children: React.ReactNode;
  className?: string;
};

const gridColsClass: Record<1 | 2 | 3, string> = {
  1: 'lg:grid-cols-1',
  2: 'lg:grid-cols-2',
  3: 'lg:grid-cols-3',
};

/* -------------------------------------------------------------------------- */
/* Context-bound controls                                                      */
/* -------------------------------------------------------------------------- */

/**
 * `<input>` that automatically adopts the surrounding `Field`'s id,
 * aria-describedby and invalid styling. All native input props are forwarded;
 * explicit `id`/`className` passed by the page win over the generated ones.
 */
export const FieldInput: React.FC<React.InputHTMLAttributes<HTMLInputElement>> = ({
  id,
  className,
  ...rest
}) => {
  const field = useFieldProps();
  return (
    <input
      id={id ?? field?.id}
      aria-describedby={field?.describedBy}
      aria-invalid={field?.invalid ? true : undefined}
      className={className ?? fieldControlClass(field?.invalid)}
      {...rest}
    />
  );
};

/** `<select>` variant of `FieldInput`. */
export const FieldSelect: React.FC<React.SelectHTMLAttributes<HTMLSelectElement>> = ({
  id,
  className,
  ...rest
}) => {
  const field = useFieldProps();
  return (
    <select
      id={id ?? field?.id}
      aria-describedby={field?.describedBy}
      aria-invalid={field?.invalid ? true : undefined}
      className={className ?? fieldControlClass(field?.invalid)}
      {...rest}
    />
  );
};

/** `<textarea>` variant of `FieldInput` (no fixed control height). */
export const FieldTextarea: React.FC<React.TextareaHTMLAttributes<HTMLTextAreaElement>> = ({
  id,
  className,
  ...rest
}) => {
  const field = useFieldProps();
  return (
    <textarea
      id={id ?? field?.id}
      aria-describedby={field?.describedBy}
      aria-invalid={field?.invalid ? true : undefined}
      className={className ?? `${fieldControlClass(field?.invalid)} py-2`}
      {...rest}
    />
  );
};

/** Responsive field grid: 1 column below `lg`, `columns` columns from `lg` up. */
export const FormRow: React.FC<FormRowProps> = ({ columns = 1, children, className }) => (
  <div className={`grid grid-cols-1 gap-section-gap ${gridColsClass[columns]} ${className ?? ''}`.trim()}>
    {children}
  </div>
);

/* -------------------------------------------------------------------------- */
/* FormSection                                                                 */
/* -------------------------------------------------------------------------- */

type FormSectionProps = {
  title?: React.ReactNode;
  description?: React.ReactNode;
  children: React.ReactNode;
  className?: string;
};

/** Grouped form block rendered as a semantic `<section>` with optional heading. */
export const FormSection: React.FC<FormSectionProps> = ({
  title,
  description,
  children,
  className,
}) => (
  <section aria-label={typeof title === 'string' ? title : undefined} className={`flex flex-col gap-3 ${className ?? ''}`.trim()}>
    {title || description ? (
      <header className="flex flex-col gap-1">
        {title ? <h3 className="text-h3 text-text-primary">{title}</h3> : null}
        {description ? <p className="text-body2 text-text-muted">{description}</p> : null}
      </header>
    ) : null}
    {children}
  </section>
);
